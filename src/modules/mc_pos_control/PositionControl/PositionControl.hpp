/**
 * @file PositionControl.hpp
 */

#pragma once

#include <lib/mathlib/mathlib.h>
#include <matrix/matrix/math.hpp>

#include <uORB/Publication.hpp>
#include <uORB/topics/trajectory_setpoint.h>
#include <uORB/topics/smc_attitude_reference.h>
#include <uORB/topics/vehicle_attitude_setpoint.h>
#include <uORB/topics/vehicle_local_position_setpoint.h>


struct PositionControlStates
{
	matrix::Vector3f position;
	matrix::Vector3f velocity;
	matrix::Vector3f acceleration;
	float yaw;
};


class PositionControl
{
public:

	PositionControl() = default;
	~PositionControl() = default;


	void setPositionGains(
		const matrix::Vector3f &P)
	{
		_gain_pos_p = P;
	}


	void setVelocityGains(
		const matrix::Vector3f &P,
		const matrix::Vector3f &I,
		const matrix::Vector3f &D);


	void setVelocityLimits(
		const float vel_horizontal,
		const float vel_up,
		float vel_down);


	void setThrustLimits(
		const float min,
		const float max);


	void setHorizontalThrustMargin(
		const float margin);


	void setTiltLimit(
		const float tilt)
	{
		_lim_tilt = tilt;
	}


	void setHoverThrust(
		const float hover_thrust)
	{
		_hover_thrust =
			math::constrain(
				hover_thrust,
				HOVER_THRUST_MIN,
				HOVER_THRUST_MAX);
	}


	void updateHoverThrust(
		const float hover_thrust_new);


	void setState(
		const PositionControlStates &states);


	void setInputSetpoint(
		const trajectory_setpoint_s &setpoint);


	void setLandDetectorState(
		const bool ground_contact,
		const bool maybe_landed,
		const bool landed,
		const bool in_descend,
		const bool has_low_throttle)
	{
		_ground_contact =
			ground_contact;

		_maybe_landed =
			maybe_landed;

		_landed =
			landed;

		_in_descend =
			in_descend;

		_has_low_throttle =
			has_low_throttle;
	}


	bool update(
		const float dt);


	void resetIntegral()
	{
		_vel_int.setZero();
	}


	void resetIntegralXY()
	{
		_vel_int.xy() =
			matrix::Vector2f();
	}


	void decoupleHorizontalAndVecticalAcceleration(
		bool val)
	{
		_decouple_horizontal_and_vertical_acceleration =
			val;
	}


	void getLocalPositionSetpoint(
		vehicle_local_position_setpoint_s
		&local_position_setpoint) const;


	void getAttitudeSetpoint(
		vehicle_attitude_setpoint_s
		&attitude_setpoint);


	/**
	 * Desired rotation matrix generated by the
	 * analytical attitude-reference generator.
	 */
	const matrix::Dcmf &
	getDesiredRotationMatrix() const
	{
		return _R_d;
	}


	/**
	 * omega_Rd =
	 *
	 * (R_d^T * R_d_dot)^vee
	 *
	 * expressed in desired body frame B_d.
	 */
	const matrix::Vector3f &
	getDesiredAngularVelocity() const
	{
		return _omega_Rd;
	}


	/**
	 * Desired angular acceleration in B_d.
	 */
	const matrix::Vector3f &
	getDesiredAngularAcceleration() const
	{
		return _omega_dot_Rd;
	}


	bool attitudeReferenceValid() const
	{
		return _attitude_reference_valid;
	}


	bool attitudeReferenceSaturated() const
	{
		return _attitude_reference_saturated;
	}


	static const trajectory_setpoint_s
	empty_trajectory_setpoint;


private:

	static constexpr float HOVER_THRUST_MIN =
		0.05f;

	static constexpr float HOVER_THRUST_MAX =
		0.9f;


	bool _inputValid();


	void _positionControl();


	void _velocityControl(
		const float dt);


	void _accelerationControl();


	void _smcPositionVelocityControl(
		const float dt);


	void _updateAttitudeReference();


	// =========================================================
	// Original PX4 gains
	//
	// Retained for compatibility.
	// =========================================================

	matrix::Vector3f _gain_pos_p;

	matrix::Vector3f _gain_vel_p;

	matrix::Vector3f _gain_vel_i;

	matrix::Vector3f _gain_vel_d;


	// =========================================================
	// Position SMC gains
	// =========================================================

	matrix::Vector3f _smc_lambda{
		1.8f,
		1.8f,
		1.5f
	};


	matrix::Vector3f _smc_k{
		1.5f,
		1.5f,
		1.2f
	};


	matrix::Vector3f _smc_eta{
		0.8f,
		0.8f,
		0.6f
	};


	/**
	 * Smooth switching gain:
	 *
	 * tanh(rho*s)
	 *
	 * Paper source uses approximately 0.9
	 * for the translational controller.
	 */
	matrix::Vector3f _smc_rho{
		0.9f,
		0.9f,
		0.9f
	};


	// =========================================================
	// Temporary safety limits
	// =========================================================

	float _smc_acc_xy_max{
		8.f
	};


	float _smc_acc_z_max{
		15.f
	};


	float _smc_landing_ground_threshold{
		0.15f
	};


	// =========================================================
	// Land detector
	// =========================================================

	bool _ground_contact{
		false
	};


	bool _maybe_landed{
		false
	};


	bool _landed{
		false
	};


	bool _in_descend{
		false
	};


	bool _has_low_throttle{
		false
	};


	// =========================================================
	// Limits
	// =========================================================

	float _lim_vel_horizontal{};

	float _lim_vel_up{};

	float _lim_vel_down{};

	float _lim_thr_min{};

	float _lim_thr_max{};

	float _lim_thr_xy_margin{};

	float _lim_tilt{};


	float _hover_thrust{};


	bool _decouple_horizontal_and_vertical_acceleration{
		true
	};


	// =========================================================
	// Current vehicle states
	// =========================================================

	matrix::Vector3f _pos;

	matrix::Vector3f _vel;

	matrix::Vector3f _vel_dot;

	matrix::Vector3f _vel_int;

	float _yaw{};


	// =========================================================
	// Desired trajectory
	// =========================================================

	matrix::Vector3f _pos_sp;

	matrix::Vector3f _vel_sp;

	matrix::Vector3f _acc_sp;

	matrix::Vector3f _jerk_sp;

	matrix::Vector3f _thr_sp;


	float _yaw_sp{};

	float _yawspeed_sp{};


	// =========================================================
	// Histories used for translational derivatives
	//
	// These are NOT angular-reference LPFs.
	// =========================================================

	matrix::Vector3f _acc_meas_prev{};

	matrix::Vector3f _jerk_sp_prev{};


	bool _acc_meas_history_initialized{
		false
	};


	bool _jerk_sp_history_initialized{
		false
	};


	// =========================================================
	// Paper-style force-direction trajectory
	//
	// Mass is omitted because a constant positive scale
	// cancels in normalization.
	// =========================================================

	matrix::Vector3f _kappa{};

	matrix::Vector3f _kappa_dot{};

	matrix::Vector3f _kappa_ddot{};


	// =========================================================
	// Analytical desired attitude trajectory
	// =========================================================

	matrix::Dcmf _R_d{};


	matrix::Vector3f _omega_Rd{};

	matrix::Vector3f _omega_dot_Rd{};


	bool _attitude_reference_valid{
		false
	};


	bool _attitude_reference_saturated{
		false
	};


	// =========================================================
	// Dedicated reference publication for attitude SMC
	// =========================================================

	uORB::Publication<smc_attitude_reference_s>
	_smc_attitude_reference_pub{
		ORB_ID(smc_attitude_reference)
	};
};